def default_display(name: str) -> Dict[str, str]:
    """取某工具的人类展示默认值（无该工具时回退到工具名本身）。"""
    d = TOOL_DISPLAY.get(str(name or "").strip()) or {}
    return {
        "display_name": d.get("display_name") or name,
        "one_liner": d.get("one_liner") or "",
        "description": d.get("description") or "",
    }


def is_known_tool(name: str) -> bool:
    return str(name or "").strip() in TOOL_DISPLAY


def optional_display(name: str) -> Optional[dict]:
    return TOOL_DISPLAY.get(str(name or "").strip())
